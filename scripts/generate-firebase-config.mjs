import fs from "node:fs";
import path from "node:path";

const projectRoot = process.cwd();
const envPath = path.join(projectRoot, ".env");

function loadDotEnvFile(filePath) {
  if (!fs.existsSync(filePath)) return;
  const fileContent = fs.readFileSync(filePath, "utf8");
  const lines = fileContent.split(/\r?\n/);

  for (const rawLine of lines) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const eqIndex = line.indexOf("=");
    if (eqIndex === -1) continue;

    const key = line.slice(0, eqIndex).trim();
    let value = line.slice(eqIndex + 1).trim();

    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }

    if (!(key in process.env)) {
      process.env[key] = value;
    }
  }
}

loadDotEnvFile(envPath);

const requiredKeys = [
  "FIREBASE_API_KEY",
  "FIREBASE_AUTH_DOMAIN",
  "FIREBASE_PROJECT_ID",
  "FIREBASE_STORAGE_BUCKET",
  "FIREBASE_MESSAGING_SENDER_ID",
  "FIREBASE_APP_ID",
];

const missingKeys = requiredKeys.filter((key) => !process.env[key]);

const targetPath = path.join(projectRoot, "js", "firebase-config.js");

if (missingKeys.length > 0) {
  console.warn(
    `[firebase-config] Missing env vars: ${missingKeys.join(", ")}. Writing placeholder config.`
  );
}

const configContent = `// Auto-generated by scripts/generate-firebase-config.mjs
// Do not hardcode private server secrets here. This file is shipped to browsers.
export const FIREBASE_WEB_CONFIG = {
  apiKey: "${process.env.FIREBASE_API_KEY || ""}",
  authDomain: "${process.env.FIREBASE_AUTH_DOMAIN || ""}",
  projectId: "${process.env.FIREBASE_PROJECT_ID || "monkey-typewriter"}",
  storageBucket: "${process.env.FIREBASE_STORAGE_BUCKET || ""}",
  messagingSenderId: "${process.env.FIREBASE_MESSAGING_SENDER_ID || ""}",
  appId: "${process.env.FIREBASE_APP_ID || ""}",
};
`;

fs.writeFileSync(targetPath, configContent, "utf8");
console.log(`[firebase-config] Wrote ${targetPath}`);
